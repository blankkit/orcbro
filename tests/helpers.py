def sliced_3mf(plates=((1, [(1, "PLA", "#FF0000", "GFA00", 3.7)]),), thumbnails=True, support=False) -> bytes:
    """Small OrcaSlicer-style sliced 3MF with slice_info.config, G-code and one thumbnail per plate."""
    plate_xml = []
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        for index, filaments in plates:
            items = "".join(
                f'<filament id="{fid}" tray_info_idx="{idx}" type="{typ}" color="{col}" used_m="1.2" used_g="{g}"/>'
                for fid, typ, col, idx, g in filaments)
            plate_xml.append(
                f'<plate><metadata key="index" value="{index}"/><metadata key="prediction" value="909"/>'
                f'<metadata key="weight" value="3.73"/><metadata key="support_used" value="{str(support).lower()}"/>'
                f'<object identify_id="1" name="cube.stl" skipped="false"/>{items}</plate>')
            archive.writestr(f"Metadata/plate_{index}.gcode", GCODE + ("; FEATURE: Support\nG1 X1 Y1 E0.1\n" if support else ""))
            if thumbnails:
                archive.writestr(f"Metadata/plate_{index}.png", b"\x89PNG fake")
        archive.writestr("Metadata/slice_info.config", f'<?xml version="1.0"?><config>{"".join(plate_xml)}</config>')
    return buffer.getvalue()


def project_3mf(filament_types=("PLA", "PETG"), printer="Bambu Lab P1S", nozzle="0.4", settings=True) -> bytes:
    """Bambu Studio/OrcaSlicer-style 3MF with project settings; settings=False creates a geometry-only
    PrusaSlicer/CAD-style file."""
    buffer = io.BytesIO()
    with zipfile.ZipFile(buffer, "w") as archive:
        archive.writestr("3D/3dmodel.model", "<model/>")
        if settings:
            archive.writestr("Metadata/model_settings.config", "<config><plate/><plate/></config>")
            archive.writestr("Metadata/project_settings.config", json.dumps({
                "printer_model": printer,
                "nozzle_diameter": [nozzle],
                "filament_type": list(filament_types),
                "filament_colour": ["#FFFFFF"] * len(filament_types),
                "filament_settings_id": [f"Generic {t}" for t in filament_types],
            }))
        else:
            archive.writestr("Metadata/Slic3r_PE.config", "; generated by PrusaSlicer 2.1.0\n")
    return buffer.getvalue()
