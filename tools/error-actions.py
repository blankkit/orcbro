#!/usr/bin/env python3
"""Generate `bridge/error_actions.json`: the buttons Bambu Studio's error dialog offers per display message.

Bambu Studio does not decide the buttons itself. `DeviceErrorDialog` looks the `print_error` code up in Bambu Lab's
HMS action table for the printer type (`hms_action_<serial prefix>.json`: `{"ecode", "device", "actions": [button
IDs]}`), shipped in Bambu Studio's `resources/hms` for newer printers and served to Bambu Studio by
`https://e.bambulab.com/hms/GetActionImage.php?d=<serial prefix>` for all of them. This script reads such files and
keeps the buttons the bridge can send (`bridge/recovery.py`, `BUTTONS`) plus the "no close button" marker (39).

    python3 tools/error-actions.py <directory with hms_action_*.json> > bridge/error_actions.json

The tables agree across printers for almost every code. `codes` holds the most common list per code; `models` holds
the few printers whose own table differs. A code missing from one printer's table uses `codes`.
"""
from __future__ import annotations

import collections
import json
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent.parent))
from bridge.recovery import BUTTONS, NO_CLOSE  # noqa: E402

# Serial number prefix (Bambu's device type) → model ID, from Bambu Studio's resources/printers (`sn_prefix`).
DEVICES = {"00M": "BL-P001", "00W": "BL-P002", "01S": "C11", "01P": "C12", "03W": "C13", "030": "N1", "039": "N2S",
           "20P": "N6", "22E": "N7", "26A": "N9", "32X": "N10", "31B": "O1C", "094": "O1D", "239": "O1E", "093": "O1S"}
# Model IDs sharing another model's table.
ALIASES = {"O1C2": "O1C"}
KEEP = set(BUTTONS) | {NO_CLOSE}


def main(directory: Path) -> None:
    tables: dict[str, dict[str, list[int]]] = {}
    versions = set()
    for path in sorted(directory.glob("hms_action_*.json")):
        device = path.stem.rsplit("_", 1)[-1]
        if device not in DEVICES:
            continue
        data = json.loads(path.read_text())
        versions.add(data.get("ver"))
        table = {}
        for item in data["data"] if isinstance(data, dict) else data:
            code = str(item.get("ecode") or "").upper()
            if len(code) != 8:
                continue  # HMS codes: Bambu Studio offers buttons only for display messages.
            buttons = [b for b in item.get("actions") or [] if b in KEEP]
            if set(buttons) - {NO_CLOSE}:
                table[code] = buttons
        tables[DEVICES[device]] = table
    votes: dict[str, collections.Counter] = collections.defaultdict(collections.Counter)
    for table in tables.values():
        for code, buttons in table.items():
            votes[code][tuple(buttons)] += 1
    codes = {code: list(counter.most_common(1)[0][0]) for code, counter in sorted(votes.items())}
    models = {}
    for model, table in sorted(tables.items()):
        own = {code: buttons for code, buttons in sorted(table.items()) if codes[code] != buttons}
        if own:
            models[model] = own
    for alias, model in ALIASES.items():
        if model in models:
            models[alias] = models[model]
    version = max(v for v in versions if v) if any(versions) else None
    lines = ["{",
             f' "about": "Bambu Studio error dialog buttons per print_error code (DeviceErrorDialog::ActionButton IDs) from'
             f' Bambu Lab\'s HMS action tables, version {version}; generated by tools/error-actions.py.",',
             ' "codes": {']
    lines += [f'  "{code}": {json.dumps(buttons)},' for code, buttons in codes.items()]
    lines[-1] = lines[-1].rstrip(",")
    lines += [" },", ' "models": {']
    entries = [f'  "{model}": {json.dumps(own, separators=(", ", ": "))},' for model, own in sorted(models.items())]
    if entries:
        entries[-1] = entries[-1].rstrip(",")
    lines += entries + [" }", "}"]
    json.loads("\n".join(lines))  # Valid JSON.
    print("\n".join(lines))


if __name__ == "__main__":
    main(Path(sys.argv[1]))
