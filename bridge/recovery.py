"""Recovery actions for printer display messages (`print_error`), as in Bambu Studio's error dialog.

Bambu Studio shows the buttons that Bambu Lab's HMS action table lists for the message code and printer type
(`error_actions.json`, generated by tools/error-actions.py). The bridge keeps the buttons it can send, under its own
names, and sends what Bambu Studio sends for them:

- resume, resume_defects, resume_solved, resume_loaded: `resume` with the message (`err`) and job (`job_id`);
- stop: `stop` with the message and job; ignore, ignore_resume: `ignore` with the message and job;
- continue, retry, retry_extrusion: `ams_control resume` (the AMS repeats the step); extruded: `ams_control done`;
  abort: `ams_control abort`;
- alarm_off: `buzzer_ctrl`; stop_drying: `auto_stop_ams_dry`.

Acknowledging (`clear_error`, Bambu Studio's OK) stays available unless Bambu requires one of the actions."""
from __future__ import annotations

import json
from pathlib import Path

# Bambu Studio's error dialog buttons (`DeviceErrorDialog::ActionButton`) → action.
BUTTONS = {2: "resume", 3: "resume_defects", 4: "resume_solved", 5: "stop", 7: "extruded", 8: "retry_extrusion",
           9: "continue", 12: "resume_loaded", 25: "ignore", 27: "ignore_resume", 28: "resume_solved",
           29: "alarm_off", 34: "retry", 35: "stop_drying", 51: "abort"}
# `REMOVE_CLOSE_BTN`: the dialog has no close button, so the printer waits for one of the actions.
NO_CLOSE = 39
# Bambu Studio offers "Retry" and "Confirm" for these codes instead of the table's buttons (`message_containing_retry`).
RETRY_CODES = {"07018004", "07018005", "07018007", "07018012", "07028012", "07038012", "07FF8012", "07FF8013"}
# AMS, AMS lite and AMS HT messages.
AMS_MODULES = {"07", "12", "18"}
# A filament change the printer can abort (`flag3` bit 13): Bambu Studio's Stop button next to Retry while the AMS
# changes filament (`ams_status` bits 8–15 = 1). Offered only without a running print.
FLAG3_CHANGE_ABORT = 1 << 13
AMS_FILAMENT_CHANGE = 1
IDLE = {"IDLE", "FINISH", "FAILED"}

COMMANDS = {
    "resume": "resume", "resume_defects": "resume", "resume_solved": "resume", "resume_loaded": "resume",
    "stop": "stop", "ignore": "ignore", "ignore_resume": "ignore",
}
AMS_CONTROL = {"continue": "resume", "retry": "resume", "retry_extrusion": "resume", "extruded": "done",
               "abort": "abort"}


def _load() -> dict:
    with open(Path(__file__).with_name("error_actions.json"), encoding="utf-8") as handle:
        table = json.load(handle)
    return {"codes": table.get("codes") or {}, "models": table.get("models") or {}}


TABLE = _load()


def _int(value) -> int | None:
    try:
        return int(float(value))
    except (TypeError, ValueError, OverflowError):
        return None


def available(value: int, model_id: str | None, raw: dict, state: str) -> tuple[list[str], bool]:
    """Actions for display message `value` in Bambu Studio's order, and whether acknowledging is also offered."""
    code = f"{value:08X}"
    if code in RETRY_CODES:
        buttons = [34]
    else:
        buttons = (TABLE["models"].get(model_id or "") or {}).get(code) or TABLE["codes"].get(code) or []
    actions: list[str] = []
    for button in buttons:
        action = BUTTONS.get(button)
        if action and action not in actions:
            actions.append(action)
    ams_status, flag3 = _int(raw.get("ams_status")), _int(raw.get("flag3"))
    if (code[:2] in AMS_MODULES and state in IDLE and "abort" not in actions and flag3 is not None
            and flag3 & FLAG3_CHANGE_ABORT and ams_status is not None and ams_status >> 8 & 0xFF == AMS_FILAMENT_CHANGE):
        actions.append("abort")
    return actions, not (NO_CLOSE in buttons and actions)


def command(action: str, value: int, job_id: str) -> tuple[str, dict]:
    """MQTT command for an available action, as Bambu Studio sends it (`command_hms_*`, `command_ams_control`)."""
    if action in COMMANDS:
        # Bambu Studio passes the message code as a decimal string.
        return ("print", {"command": COMMANDS[action], "err": str(value), "param": "reserve", "job_id": job_id})
    if action in AMS_CONTROL:
        return ("print", {"command": "ams_control", "param": AMS_CONTROL[action]})
    if action == "alarm_off":
        return ("print", {"command": "buzzer_ctrl", "mode": 0})
    if action == "stop_drying":
        return ("print", {"command": "auto_stop_ams_dry"})
    raise KeyError(action)
